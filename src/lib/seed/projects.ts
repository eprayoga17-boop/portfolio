import type { CategoryId, Project, ProjectImage } from "@/lib/types";

/**
 * Seed content, rewritten from Erik's 2025 portfolio PDF.
 * The site falls back to this when Supabase is not configured, and
 * scripts/generate-seed-sql.mjs turns it into supabase/seed.sql.
 *
 * Years and regions are only filled in where the PDF or CV states them.
 * Everything else is left null for Erik to complete in the admin panel.
 */

type SeedInput = {
  slug: string;
  title: string;
  client: string;
  category: CategoryId;
  region?: string;
  year?: number;
  role: string;
  services: string[];
  summary: string;
  body: string;
  accent: string;
  featured?: boolean;
  externalUrl?: string;
  cover: [number, number];
  alts: string[];
};

function build(input: SeedInput, index: number): Project {
  const images: ProjectImage[] = input.alts.map((alt, i) => ({
    id: `${input.slug}-${i + 1}`,
    path: `/seed/${input.slug}/${String(i + 1).padStart(2, "0")}.webp`,
    alt,
    width: 1920,
    height: 1080,
  }));
  return {
    id: `seed-${input.slug}`,
    slug: input.slug,
    title: input.title,
    client: input.client,
    category: input.category,
    year: input.year ?? null,
    region: input.region ?? null,
    role: input.role,
    services: input.services,
    summary: input.summary,
    body: input.body,
    accent: input.accent,
    featured: input.featured ?? false,
    published: true,
    sortOrder: index,
    externalUrl: input.externalUrl ?? null,
    cover: {
      id: `${input.slug}-cover`,
      path: `/seed/${input.slug}/cover.webp`,
      alt: input.alts[0],
      width: input.cover[0],
      height: input.cover[1],
    },
    images,
  };
}

