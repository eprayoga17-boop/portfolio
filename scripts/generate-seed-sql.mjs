// Generates supabase/seed.sql from src/lib/seed/projects.ts.
// Run: node scripts/generate-seed-sql.mjs   (Node 22.18+ strips TS types natively)
//
// Seed images point at /seed/... files bundled in /public, so the site works
// immediately. Replace them with uploads from the admin panel whenever.
import { writeFileSync } from "node:fs";
import { seedProjects } from "../src/lib/seed/projects.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

let sql = `-- Generated by scripts/generate-seed-sql.mjs. Safe to re-run: existing slugs are skipped.\n\n`;
for (const p of seedProjects) {
  sql += `with ins as (
  insert into public.projects (slug, title, client, category, year, region, role, services, summary, body, accent, featured, published, sort_order, external_url, cover_path, cover_alt, cover_width, cover_height)
  values (${q(p.slug)}, ${q(p.title)}, ${q(p.client)}, ${q(p.category)}, ${p.year ?? "null"}, ${q(p.region)}, ${q(p.role)}, ${arr(p.services)}, ${q(p.summary)}, ${q(p.body)}, ${q(p.accent)}, ${p.featured}, true, ${p.sortOrder}, ${q(p.externalUrl)}, ${q(p.cover?.path)}, ${q(p.cover?.alt)}, ${p.cover?.width ?? "null"}, ${p.cover?.height ?? "null"})
  on conflict (slug) do nothing
  returning id
)
insert into public.project_images (project_id, path, alt, width, height, sort_order)
select ins.id, v.path, v.alt, v.width, v.height, v.sort_order from ins, (values
${p.images.map((img, i) => `  (${q(img.path)}, ${q(img.alt)}, ${img.width}, ${img.height}, ${i})`).join(",\n")}
) as v(path, alt, width, height, sort_order);\n\n`;
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${seedProjects.length} projects to supabase/seed.sql`);
